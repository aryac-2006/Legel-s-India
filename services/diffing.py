"""Genuine text comparison with difflib. AI (if used) only explains detected differences."""
import difflib, html, re
from services.documents import extract_entities


def paragraphs(text):
    out = []
    for p in re.split(r"\n\s*\n|(?<=[.;:])\n", text or ""):
        p = re.sub(r"\s+", " ", p).strip()
        if p:
            out.append(p)
    return out


def word_diff_html(a, b):
    aw, bw = a.split(), b.split()
    sm = difflib.SequenceMatcher(None, aw, bw, autojunk=False)
    left, right = [], []
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        A, B = html.escape(" ".join(aw[i1:i2])), html.escape(" ".join(bw[j1:j2]))
        if tag == "equal":
            left.append(A); right.append(B)
        else:
            if A: left.append(f'<del style="background:#f8d7da">{A}</del>')
            if B: right.append(f'<ins style="background:#d1e7dd;text-decoration:none">{B}</ins>')
    return " ".join(left), " ".join(right)


def compare(a, b, modified_threshold=0.5):
    """Paragraph-level diff. Returns dict with added, removed, modified, unchanged counts and details."""
    pa, pb = paragraphs(a), paragraphs(b)
    sm = difflib.SequenceMatcher(None, pa, pb, autojunk=False)
    added, removed, modified, same = [], [], [], 0
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == "equal":
            same += i2 - i1
        elif tag == "delete":
            removed += pa[i1:i2]
        elif tag == "insert":
            added += pb[j1:j2]
        else:                                    # replace: pair paragraphs by best similarity
            left, right = list(pa[i1:i2]), list(pb[j1:j2])
            for l in left:
                best, score = None, 0.0
                for r in right:
                    s = difflib.SequenceMatcher(None, l, r).ratio()
                    if s > score:
                        best, score = r, s
                if best is not None and score >= modified_threshold:
                    modified.append({"before": l, "after": best, "similarity": round(score, 3)}); right.remove(best)
                else:
                    removed.append(l)
            added += right
    ea, eb = extract_entities(a), extract_entities(b)
    facts = {}
    for key in ("dates", "amounts", "possible_parties"):
        sa, sb = set(ea[key]), set(eb[key])
        facts[key] = {"only_in_a": sorted(sa - sb), "only_in_b": sorted(sb - sa), "common": sorted(sa & sb)}
    ratio = difflib.SequenceMatcher(None, a or "", b or "", autojunk=False).quick_ratio() if (a or b) else 1.0
    return {"identical": (a or "").strip() == (b or "").strip(), "added": added, "removed": removed, "modified": modified,
            "unchanged": same, "facts": facts, "similarity_upper_bound": round(ratio, 3)}


def explain_changes_prompt(result):
    """Text handed to an optional AI explainer: only detected differences, never the full documents."""
    lines = [f"MODIFIED: '{m['before'][:200]}' -> '{m['after'][:200]}'" for m in result["modified"][:10]]
    lines += [f"ADDED: '{x[:200]}'" for x in result["added"][:10]] + [f"REMOVED: '{x[:200]}'" for x in result["removed"][:10]]
    return "\n".join(lines)


def report_text(name_a, name_b, r):
    out = [f"DOCUMENT COMPARISON REPORT", f"A: {name_a}", f"B: {name_b}", "",
           f"Unchanged paragraphs: {r['unchanged']} | Added: {len(r['added'])} | Removed: {len(r['removed'])} | Modified: {len(r['modified'])}", ""]
    for m in r["modified"]:
        out += ["MODIFIED", f"  Before: {m['before']}", f"  After:  {m['after']}", ""]
    out += [f"ADDED: {x}" for x in r["added"]] + [""] + [f"REMOVED: {x}" for x in r["removed"]]
    out += ["", "FACT DIFFERENCES"] + [f"{k}: only in A {v['only_in_a']} | only in B {v['only_in_b']}" for k, v in r["facts"].items()]
    out += ["", "Generated by text comparison (difflib). Review by a qualified person is recommended."]
    return "\n".join(out)
